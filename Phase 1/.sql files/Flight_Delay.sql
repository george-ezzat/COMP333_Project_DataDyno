OriginCityName char(25),
DestCityName char(25),
DepTime int,
DepDelay int,
DepDelayMinutes int, 
TaxiOut int,
Taxiin int,
ArrTime int, 
ArrDelay int,
ArrDelayMinutes int,
CRSElapsedTime int,
ActualElapsedTime int,
AirTime int,
