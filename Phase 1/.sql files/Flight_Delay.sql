OriginCityName char(25),
DestCityName char(25),
CRSDepTime int,
DepTime int,
DepDelay int,
DepDelayMinutes int, 
TaxiOut int,
WheelsOff int, 
WheelsOn int, 
Taxiin int,
CRSArrTime int, 
ArrTime int, 
ArrDelay int,
ArrDelayMinutes int,
